// scripts/build-design-system.mjs — builds the design system's component files from the app's own code:
//   <out>/components/bundle.js  one classic script, window.MockupLab = { Button, Segmented, … } (React from the page)
//   <out>/components/bundle.css the app's compiled styles, minus the values tokens.json declares
// Usage: npm run build && node scripts/build-design-system.mjs <out-dir>   (the published system: DESIGN.md)
import { build } from 'vite';
import react from '@vitejs/plugin-react';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath, URL } from 'node:url';

const out = process.argv[2];
if (!out) throw new Error('usage: node scripts/build-design-system.mjs <out-dir>');
mkdirSync(`${out}/components`, { recursive: true });

// the cards, in order (TooltipProvider is exported too, but a provider gets no card)
const NAMES = ['Logo', 'LogoMark', 'Button', 'IconButton', 'Tooltip', 'Kbd', 'GroupTitle', 'Section', 'Field', 'Segmented', 'Slider', 'ColorField', 'Spinner', 'Switch', 'Advanced', 'Chip', 'Sheet'];
// react/jsx-runtime from the page's React (the bundle carries no React of its own)
const header = `/* @ds-bundle: ${JSON.stringify({ format: 4, namespace: 'MockupLab', components: NAMES.map((name) => ({ name })) })} */\n`;
const banner = `var __MLJSX=(function(R){function j(t,p,k){return R.createElement(t,k===undefined?p:Object.assign({},p,{key:k}))}return{jsx:j,jsxs:j,Fragment:R.Fragment}})(window.React);`;

await build({
  configFile: false,
  logLevel: 'warn',
  plugins: [react()],
  resolve: { alias: { '@': fileURLToPath(new URL('../src', import.meta.url)) } },
  define: { 'process.env.NODE_ENV': '"production"', __BUILD_ID__: '"design-system"' },
  build: {
    outDir: `${out}/.build`,
    emptyOutDir: true,
    minify: true,
    lib: { entry: fileURLToPath(new URL('./design-system/entry.tsx', import.meta.url)), formats: ['iife'], name: 'MockupLab', fileName: () => 'bundle.js' },
    rollupOptions: {
      external: ['react', 'react-dom', 'react/jsx-runtime', 'react-dom/client'],
      output: { globals: { react: 'React', 'react-dom': 'ReactDOM', 'react-dom/client': 'ReactDOM', 'react/jsx-runtime': '__MLJSX' }, banner },
    },
  },
});
let js = readFileSync(`${out}/.build/bundle.js`, 'utf8');
// consumers inline it: no literal end-of-script or comment opener
js = js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
// line 1: the header the design system reads (minification drops comments, so it goes on after)
writeFileSync(`${out}/components/bundle.js`, header + js);

// styles: the app's compiled CSS (every utility the components use), without the custom properties tokens.json
// owns — tokens.css declares those, so a value changed in the design system wins
const css = readdirSync('dist/assets').find((f) => /^(index|main)-.*\.css$/.test(f));
if (!css) throw new Error('no dist/assets/main-*.css: run npm run build first');
const tokens = JSON.parse(readFileSync(`${out}/tokens.json`, 'utf8'));
const owned = new Set([...tokens.color.tokens, ...(tokens.shadow?.tokens ?? [])].map((t) => t.name));
let sheet = readFileSync(`dist/assets/${css}`, 'utf8');
sheet = sheet.replace(/(^|[;{\s])--([\w-]+):([^;}]*)(;?)/g, (m, lead, name, _v, semi) => (owned.has(name) ? lead : m));
// fonts come from the system's fonts/ (tokens.css), not the app's hashed files
sheet = sheet.replace(/@font-face\{[^}]*\}/g, '');
writeFileSync(`${out}/components/bundle.css`, `/* MockupLab — app styles (generated by scripts/build-design-system.mjs) */\n${sheet}`);
console.log(`bundle.js ${Math.round(js.length / 1024)} KB · bundle.css ${Math.round(sheet.length / 1024)} KB`);
