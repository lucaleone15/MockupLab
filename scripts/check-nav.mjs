// scripts/check-nav.mjs — hash ⇄ screen, project mode follows, back button, unavailable screens.
import { openApp, check, done } from './lib/app.mjs';
const { browser, page, errors } = await openApp();
const st = () => page.evaluate(() => ({ screen: window.__mockuplab.ui.getState().screen, mode: window.__mockuplab.project.getState().mode, hash: location.pathname + location.hash }));
let s = await st();
check(s.screen === 'home' && s.hash === '/', 'no path → home');
await page.evaluate(() => (location.hash = '#/photo'));
await page.waitForTimeout(200);
s = await st();
check(s.screen === 'photo' && s.mode === 'photo', '#/photo → photo screen, photo mode');
await page.evaluate(() => (location.hash = '#/studio'));
await page.waitForTimeout(200);
s = await st();
check(s.screen === 'studio' && s.mode === 'scene', '#/studio → studio screen, scene mode');
const tabs = await page.getByTestId('mode-switch').getByRole('radio').allInnerTexts();
check(tabs.join() === 'Studio,Rapide,Projet,Photo', `header order (${tabs})`);
await page.getByTestId('mode-switch').getByRole('radio', { name: 'Rapide' }).hover();
await page.waitForTimeout(900);
check(await page.getByRole('tooltip').filter({ hasText: 'mock-ups tout faits' }).first().isVisible().catch(() => false), 'hovering a mode explains its role');
await page.mouse.move(0, 400);
await page.goBack();
await page.waitForTimeout(200);
check((await st()).screen === 'photo', 'back button returns to photo');
await page.evaluate(() => (location.hash = '#/rapide'));
await page.waitForTimeout(200);
s = await st();
check(s.screen === 'quick', '#/rapide → quick');
await page.evaluate(() => (location.hash = '#/nimporte'));
await page.waitForTimeout(200);
s = await st();
check(s.screen === 'home' && s.hash === '/', 'unknown address → home');
await page.evaluate(() => (location.hash = '#/studio'));
await page.waitForTimeout(300);
const radios = await page.getByTestId('mode-switch').getByRole('radio').allTextContents();
check(JSON.stringify(radios.map((r) => r.trim())) === JSON.stringify(['Studio', 'Rapide', 'Projet', 'Photo']), `mode switch: ${radios}`);
check(!(await page.getByTestId('mode-switch').getByRole('radio', { name: 'Rapide' }).isDisabled()), 'Rapide available');
await page.getByTestId('mode-switch').getByRole('radio', { name: 'Photo' }).click();
await page.waitForTimeout(200);
check((await st()).hash === '/photo', 'mode switch → /photo');
await page.getByRole('button', { name: 'Plus' }).click();
check(await page.getByRole('menuitem', { name: /Raccourcis clavier/ }).isVisible(), '··· menu lists shortcuts');
await page.keyboard.press('Escape');
// keyboard shortcuts do nothing on home
await page.evaluate(() => (location.hash = '#/'));
await page.waitForTimeout(200);
const before = await page.evaluate(() => window.__mockuplab.project.getState().items.length);
await page.keyboard.press('Backspace');
await page.keyboard.press('r');
const after = await page.evaluate(() => window.__mockuplab.project.getState().items.length);
check(before === after, 'Delete on home does not remove the device');
await done(browser, errors);
